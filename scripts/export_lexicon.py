#!/usr/bin/env python3
"""sherpa.db symbol names -> src/lib/keyboard/lexicon.personal.ts (letters only)."""
import re, sqlite3
from pathlib import Path
from collections import Counter

ROOT = Path(__file__).resolve().parent.parent
DB   = Path.home() / ".meboard" / "sherpa.db"
BASE = (ROOT / "src/lib/keyboard/lexicon.ts").read_text()
OUT  = ROOT / "src/lib/keyboard/lexicon.personal.ts"
base_words = set(re.findall(r'"([a-z\']+)"', BASE.split("export const LEXICON")[0] + BASE))

names = [r[0] for r in sqlite3.connect(DB).execute(
    "SELECT DISTINCT name FROM symbols WHERE name NOT LIKE '\\_\\_%' ESCAPE '\\' AND filepath NOT LIKE '%public-apis%' AND filepath NOT LIKE '%site-packages%' AND filepath NOT LIKE '%/tests/%' AND filepath NOT LIKE '%/vendor/%' AND filepath NOT LIKE '%/.gemini/%'")]
cnt = Counter()
for n in names:
    n = re.sub(r"([a-z])([A-Z])", r"\1_\2", n)
    for part in {p.lower() for p in re.split(r"[^A-Za-z]+", n)}:
        if 4 <= len(part) <= 14 and part not in base_words:
            cnt[part] += 1

DENY = set("city attack pitch monster course legal meeting social visit knot clip".split())
top = [w for w, c in cnt.most_common(250) if c >= 8 and w not in DENY]
body = ",\n".join(f'  "{w}"' for w in top)
OUT.write_text("// generated by scripts/export_lexicon.py -- do not hand-edit\n"
               f"export const PERSONAL_LEXICON: readonly string[] = [\n{body},\n];\n")
print(f"{len(top)} words -> {OUT}")
print(" ".join(top))
